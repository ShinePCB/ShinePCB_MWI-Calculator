/* Builds browser material data from SQLite. GPL-3.0-or-later */
import { writeFile } from "node:fs/promises";
import { readMaterials } from "./materials-db.mjs";

const materials = readMaterials();
if (!materials.length) throw new Error("SQLite contains no calculator materials");
const out = `/* Generated by scripts/build-materials.mjs from data/sunden-materials.sqlite – do not edit.
 * 晟电新材料 SUNDEN 产品规格书（典型值）。dk / df @ 10 GHz (IPC-TM-650 2.5.5.5)，designDk @ 8–40 GHz（差分相位长度法），
 * kth W/(m·K) @ 80 ℃，tcdk ppm/℃，dkByThickness 为标称厚度 (mm) 对应 Dk，cured 为粘结片固化厚度 (mm)。 */
export const MATERIALS = ${JSON.stringify(materials, null, 1)};
`;
await writeFile(new URL("../dist/materials.js", import.meta.url), out);
console.log(`materials.js: ${materials.length} materials (SQLite)`);
